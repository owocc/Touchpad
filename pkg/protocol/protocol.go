package protocol

import (
	"encoding/binary"
	"errors"
	"math"
)

// Magic byte identifying Touchpad protocol frames ('T' = 0x54).
const MagicByte uint8 = 0x54

// Current protocol version.
const ProtocolVersion uint8 = 0x01

// FixedHeaderSize is the size of the base binary packet frame in bytes.
// 24 bytes fixed frame:
//  0..3:  Magic (1B) | Version (1B) | MsgType (1B) | Flags (1B)
//  4..7:  SequenceNumber (4B uint32)
//  8..11: TimestampMicros (4B uint32)
// 12..15: DeltaX (4B float32)
// 16..19: DeltaY (4B float32)
// 20:     Phase (1B uint8)
// 21:     MomentumPhase (1B uint8)
// 22:     FingerCount (1B uint8)
// 23:     AuxValue (1B int8 or button identifier)
const FixedPacketSize = 24

// MsgType identifies the kind of input or control event.
type MsgType uint8

const (
	MsgNone         MsgType = 0x00
	MsgPointerMove  MsgType = 0x01 // Relative mouse cursor motion
	MsgMouseButton  MsgType = 0x02 // Mouse button press/release/click
	MsgScroll       MsgType = 0x03 // 2-finger or edge scroll
	MsgPinchRotate  MsgType = 0x04 // 2-finger zoom/rotate
	MsgSystemSwipe  MsgType = 0x05 // 3-finger / 4-finger navigation swipe
	MsgPairRequest  MsgType = 0x10 // Client requests pairing
	MsgPairResponse MsgType = 0x11 // Host responds with pairing result
	MsgHeartbeat    MsgType = 0x12 // Keepalive & connection watchdog
	MsgResetState   MsgType = 0x13 // Release all buttons and halt inertia
	MsgPing         MsgType = 0xFE // Latency probe (echoes back timestamp)
	MsgPong         MsgType = 0xFF // Latency probe response
)

// Flags bitmask
const (
	FlagReliable  uint8 = 0x80 // Packet requires acknowledgement / was retransmitted
	FlagEncrypted uint8 = 0x40 // Packet payload is encrypted
	FlagSynthetic uint8 = 0x20 // Generated by momentum / inertia engine
)

// Touch and scroll phase constants
type Phase uint8

const (
	PhaseNone      Phase = 0
	PhaseBegan     Phase = 1
	PhaseChanged   Phase = 2
	PhaseEnded     Phase = 4
	PhaseCancelled Phase = 8
)

// Momentum (inertia) phase constants
type MomentumPhase uint8

const (
	MomentumNone     MomentumPhase = 0
	MomentumBegin    MomentumPhase = 1
	MomentumContinue MomentumPhase = 2
	MomentumEnd      MomentumPhase = 3
)

// Mouse button identifiers
const (
	ButtonLeft   uint8 = 1
	ButtonRight  uint8 = 2
	ButtonMiddle uint8 = 3
)

// Mouse button action phase
const (
	ButtonDown  uint8 = 1
	ButtonUp    uint8 = 2
	ButtonClick uint8 = 3
)

// Packet represents a parsed touchpad event frame.
type Packet struct {
	Version         uint8
	Type            MsgType
	Flags           uint8
	SequenceNumber  uint32
	TimestampMicros uint32
	DeltaX          float32
	DeltaY          float32
	Phase           Phase
	MomentumPhase   MomentumPhase
	FingerCount     uint8
	AuxValue        int8
}

var (
	ErrPacketTooShort = errors.New("touchpad: packet buffer too short")
	ErrInvalidMagic   = errors.New("touchpad: invalid magic byte")
	ErrBadVersion     = errors.New("touchpad: unsupported protocol version")
)

// Encode serializes the packet into a fixed 24-byte slice.
// If dst has capacity >= FixedPacketSize, it is used without heap allocation.
func (p *Packet) Encode(dst []byte) []byte {
	if len(dst) < FixedPacketSize {
		dst = make([]byte, FixedPacketSize)
	} else {
		dst = dst[:FixedPacketSize]
	}

	dst[0] = MagicByte
	if p.Version == 0 {
		dst[1] = ProtocolVersion
	} else {
		dst[1] = p.Version
	}
	dst[2] = uint8(p.Type)
	dst[3] = p.Flags

	binary.LittleEndian.PutUint32(dst[4:8], p.SequenceNumber)
	binary.LittleEndian.PutUint32(dst[8:12], p.TimestampMicros)

	binary.LittleEndian.PutUint32(dst[12:16], math.Float32bits(p.DeltaX))
	binary.LittleEndian.PutUint32(dst[16:20], math.Float32bits(p.DeltaY))

	dst[20] = uint8(p.Phase)
	dst[21] = uint8(p.MomentumPhase)
	dst[22] = p.FingerCount
	dst[23] = uint8(p.AuxValue)

	return dst
}

// Decode deserializes the packet from raw bytes.
func (p *Packet) Decode(src []byte) error {
	if len(src) < FixedPacketSize {
		return ErrPacketTooShort
	}
	if src[0] != MagicByte {
		return ErrInvalidMagic
	}
	if src[1] != ProtocolVersion {
		return ErrBadVersion
	}

	p.Version = src[1]
	p.Type = MsgType(src[2])
	p.Flags = src[3]
	p.SequenceNumber = binary.LittleEndian.Uint32(src[4:8])
	p.TimestampMicros = binary.LittleEndian.Uint32(src[8:12])
	p.DeltaX = math.Float32frombits(binary.LittleEndian.Uint32(src[12:16]))
	p.DeltaY = math.Float32frombits(binary.LittleEndian.Uint32(src[16:20]))
	p.Phase = Phase(src[20])
	p.MomentumPhase = MomentumPhase(src[21])
	p.FingerCount = src[22]
	p.AuxValue = int8(src[23])

	return nil
}

// SequenceTracker handles sequence ordering, dropping obsolete packets
// for unreliable motion streams while ensuring critical packets are not dropped.
type SequenceTracker struct {
	lastSeq uint32
	hasSeq  bool
}

// ShouldProcess evaluates whether a packet should be processed or silently dropped.
// For continuous motion packets (PointerMove, Scroll PhaseChanged/MomentumContinue),
// old/out-of-order packets are dropped.
// Critical state transitions (Began, Ended, ButtonDown/Up, ResetState) are always processed.
func (st *SequenceTracker) ShouldProcess(pkt *Packet) bool {
	// Critical packets always process and update sequence
	if pkt.Type == MsgResetState ||
		pkt.Type == MsgMouseButton ||
		pkt.Type == MsgHeartbeat ||
		pkt.Type == MsgPing ||
		pkt.Type == MsgPong ||
		(pkt.Flags&FlagReliable) != 0 ||
		pkt.Phase == PhaseBegan ||
		pkt.Phase == PhaseEnded ||
		pkt.Phase == PhaseCancelled ||
		pkt.MomentumPhase == MomentumBegin ||
		pkt.MomentumPhase == MomentumEnd {
		st.update(pkt.SequenceNumber)
		return true
	}

	// For continuous moves: drop if older than or equal to last seen sequence
	if !st.hasSeq {
		st.update(pkt.SequenceNumber)
		return true
	}

	diff := int32(pkt.SequenceNumber - st.lastSeq)
	if diff <= 0 {
		// Stale / out-of-order packet in motion stream -> drop
		return false
	}

	st.lastSeq = pkt.SequenceNumber
	return true
}

func (st *SequenceTracker) update(seq uint32) {
	st.lastSeq = seq
	st.hasSeq = true
}

// Reset resets the tracker state.
func (st *SequenceTracker) Reset() {
	st.lastSeq = 0
	st.hasSeq = false
}
